"""Issue draft title and body (PRD 12.2). Pure functions: no database, no network.

The body may end up on a PUBLIC repository, so:
- the `secrets` item never includes paths, line numbers or pattern ids;
- every "@" in rule messages is defused with a zero-width space so nobody gets pinged;
- repo-derived strings that a rule wants to quote go through `safe_inline`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date

ZWSP = "​"
MAX_BODY = 60_000
MAX_TITLE = 256
TRUNCATED_MARKER = "\n\n_(truncated)_"
SECRETS_RULE_ID = "secrets"
SECRETS_ITEM = (
    "Potential secrets were detected. A maintainer should review the findings in GitWell "
    "privately, rotate the affected credentials and purge them from git history."
)
_MENTION_RE = re.compile(r"@(?!" + ZWSP + ")")


@dataclass(frozen=True)
class DraftItem:
    rule_id: str
    name: str
    status: str  # "fail" or "warn"
    message: str
    fix_tip: str


def defuse_mentions(text: str) -> str:
    """Insert a zero-width space after every "@" (idempotent), so @-mentions do not ping."""
    return _MENTION_RE.sub("@" + ZWSP, text)


def safe_inline(value: str) -> str:
    """Quote a repo-derived string as inline code: backticks removed, "@" defused."""
    return "`" + defuse_mentions(value.replace("`", "")) + "`"


def indent(text: str, prefix: str = "  ") -> str:
    """Indent EVERY line (a list item's continuation)."""
    return "\n".join(prefix + line for line in text.splitlines())


def build_title(count: int, score: int | None) -> str:
    suffix = "score unavailable" if score is None else f"score {score}/100"
    title = f"GitWell: {count} quality check(s) need attention ({suffix})"
    return title[:MAX_TITLE]


def _item(item: DraftItem) -> str:
    text = SECRETS_ITEM if item.rule_id == SECRETS_RULE_ID else defuse_mentions(item.message)
    head = f"- [ ] **{item.name}**: {text}"
    return head + ("\n" + indent(item.fix_tip) if item.fix_tip.strip() else "")


def build_body(
    items: list[DraftItem],
    *,
    commit_sha: str | None,
    scanned_on: date,
    score: int | None,
    grade: str | None,
) -> str:
    """Items must already be in display order."""
    short_sha = commit_sha[:7] if commit_sha else "unknown"
    parts = [
        f"GitWell scanned this repository at commit `{short_sha}` on {scanned_on.isoformat()} "
        "and found the following:"
    ]
    failing = [i for i in items if i.status == "fail"]
    warnings = [i for i in items if i.status == "warn"]
    if failing:
        parts.append("## ❌ Failing\n" + "\n".join(_item(i) for i in failing))
    if warnings:
        parts.append("## ⚠️ Warnings\n" + "\n".join(_item(i) for i in warnings))
    footer = (
        "_Generated by GitWell. Score: unavailable._"
        if score is None
        else f"_Generated by GitWell. Score: {score}/100 ({grade})._"
    )
    parts.append("---\n" + footer)
    body = "\n\n".join(parts)
    if len(body) > MAX_BODY:
        body = body[: MAX_BODY - len(TRUNCATED_MARKER)] + TRUNCATED_MARKER
    return body
