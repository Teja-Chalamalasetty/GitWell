from datetime import date

from app.services.issue_body import (
    MAX_BODY,
    ZWSP,
    DraftItem,
    build_body,
    build_title,
    defuse_mentions,
    indent,
    safe_inline,
)

SHA = "abcdef1234567890abcdef1234567890abcdef12"
DAY = date(2026, 11, 18)


def item(
    rule_id: str, status: str, message: str, tip: str = "Do the thing.", name: str = ""
) -> DraftItem:
    return DraftItem(rule_id, name or rule_id.title(), status, message, tip)


def body(items: list[DraftItem], score: int | None = 41, grade: str | None = "D") -> str:
    return build_body(items, commit_sha=SHA, scanned_on=DAY, score=score, grade=grade)


# ---- title ---------------------------------------------------------------------------------


def test_title_format() -> None:
    assert build_title(3, 41) == "GitWell: 3 quality check(s) need attention (score 41/100)"
    assert build_title(1, 0) == "GitWell: 1 quality check(s) need attention (score 0/100)"


def test_title_when_the_score_is_unavailable() -> None:
    assert build_title(2, None) == "GitWell: 2 quality check(s) need attention (score unavailable)"


# ---- body structure ------------------------------------------------------------------------


def test_body_matches_the_documented_layout_exactly() -> None:
    text = body(
        [
            item(
                "tests", "fail", "No test files or test directories found.", "Add pytest.", "Tests"
            ),
            item(
                "readme",
                "warn",
                "README is very short (84 characters).",
                "Write more.\nSecond line.",
                "README",
            ),
        ]
    )
    assert text == (
        "GitWell scanned this repository at commit `abcdef1` on 2026-11-18 "
        "and found the following:\n"
        "\n"
        "## ❌ Failing\n"
        "- [ ] **Tests**: No test files or test directories found.\n"
        "  Add pytest.\n"
        "\n"
        "## ⚠️ Warnings\n"
        "- [ ] **README**: README is very short (84 characters).\n"
        "  Write more.\n"
        "  Second line.\n"
        "\n"
        "---\n"
        "_Generated by GitWell. Score: 41/100 (D)._"
    )


def test_empty_sections_are_omitted() -> None:
    only_fail = body([item("tests", "fail", "m")])
    assert "## ❌ Failing" in only_fail and "Warnings" not in only_fail
    only_warn = body([item("tests", "warn", "m")])
    assert "## ⚠️ Warnings" in only_warn and "Failing" not in only_warn


def test_items_keep_the_order_they_are_given() -> None:
    items = [item(f"r{i}", "fail", f"message {i}", name=f"Rule {i}") for i in range(5)]
    text = body(items)
    positions = [text.index(f"**Rule {i}**") for i in range(5)]
    assert positions == sorted(positions)


def test_short_sha_is_seven_characters_and_missing_sha_is_handled() -> None:
    assert "`abcdef1`" in body([item("a", "fail", "m")])
    text = build_body([item("a", "fail", "m")], commit_sha=None, scanned_on=DAY, score=1, grade="F")
    assert "`unknown`" in text


def test_footer_when_the_score_is_unavailable() -> None:
    assert body([item("a", "fail", "m")], score=None, grade=None).endswith(
        "_Generated by GitWell. Score: unavailable._"
    )


def test_every_line_of_a_fix_tip_is_indented_two_spaces() -> None:
    tip = "Line one.\n\n```yaml\nname: CI\n```"
    text = body([item("ci", "fail", "No CI.", tip)])
    lines = text.splitlines()
    start = lines.index("- [ ] **Ci**: No CI.")
    tip_lines = lines[start + 1 : start + 1 + 5]
    assert tip_lines == ["  Line one.", "  ", "  ```yaml", "  name: CI", "  ```"]


def test_an_item_without_a_fix_tip_has_no_continuation() -> None:
    text = body([item("a", "fail", "m", tip="")])
    assert "- [ ] **A**: m\n\n---" in text


# ---- secrets (the body may be public) ------------------------------------------------------


def test_the_secrets_item_never_includes_findings_paths_or_patterns() -> None:
    leaky = (
        "2 potential secret(s) found in 1 file(s). src/@scope/keys.py:12 aws_access_key_id "
        "deploy/id_rsa private_key"
    )
    text = body(
        [
            item(
                "secrets",
                "fail",
                leaky,
                "**Revoke and rotate the credential first.**",
                "No committed secrets",
            )
        ]
    )
    assert (
        "- [ ] **No committed secrets**: Potential secrets were detected. "
        "A maintainer should review" in text
    )
    for forbidden in (
        "keys.py",
        "aws_access_key_id",
        "id_rsa",
        "private_key",
        "src/",
        ":12",
        "potential secret(s)",
    ):
        assert forbidden not in text
    assert "rotate the affected credentials and purge them from git history." in text
    assert "  **Revoke and rotate the credential first.**" in text  # the tip still follows


def test_secrets_warning_gets_the_same_text() -> None:
    text = body(
        [
            item(
                "secrets",
                "warn",
                "1 potential secret(s) found in 1 file(s).",
                "tip",
                "No committed secrets",
            )
        ]
    )
    assert "Potential secrets were detected." in text and "found in 1 file" not in text


# ---- mention and injection safety ----------------------------------------------------------


def test_at_signs_in_messages_are_defused() -> None:
    text = body([item("tests", "fail", "Missing tests in packages/@scope/pkg and by @someone")])
    assert f"@{ZWSP}scope" in text and f"@{ZWSP}someone" in text
    assert "@scope" not in text and "@someone" not in text


def test_defuse_is_idempotent() -> None:
    once = defuse_mentions("hi @bob and @alice")
    assert defuse_mentions(once) == once
    assert once.count(ZWSP) == 2


def test_fix_tips_are_left_untouched_so_copy_paste_examples_still_work() -> None:
    tip = "```yaml\n- uses: actions/checkout@v4\n```"
    text = body([item("ci", "fail", "No CI.", tip, "CI")])
    assert "actions/checkout@v4" in text  # no zero-width space inside the example
    assert ZWSP not in text


def test_safe_inline_removes_backticks_and_defuses_mentions() -> None:
    assert safe_inline("a`b`c") == "`abc`"
    assert safe_inline("src/@scope/x.py") == f"`src/@{ZWSP}scope/x.py`"
    assert safe_inline("`; rm -rf `") == "`; rm -rf `"
    assert "`" not in safe_inline("x`y")[1:-1]


def test_indent_helper() -> None:
    assert indent("a\nb") == "  a\n  b"
    assert indent("a", ">>") == ">>a"


# ---- size limit ----------------------------------------------------------------------------


def test_an_oversized_body_is_truncated_with_a_marker() -> None:
    huge = [item(f"r{i}", "fail", "x" * 500, "tip " * 200, f"Rule {i}") for i in range(200)]
    text = body(huge)
    assert len(text) == MAX_BODY
    assert text.endswith("\n\n_(truncated)_")


def test_a_normal_body_is_not_truncated() -> None:
    assert "_(truncated)_" not in body([item("a", "fail", "m")])
