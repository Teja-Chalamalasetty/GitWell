def test_draft_lists_every_fail_and_warn_rule_in_order_with_the_right_title(world: World) -> None:
    draft = world.draft()
    assert draft["status"] == "drafted"
    assert draft["repo_full_name"] == "o/r" and draft["repo_is_private"] is False
    assert draft["scan_id"] == world.scan_id and draft["post_attempts"] == 0
    assert draft["github_issue_number"] is None and draft["last_error"] is None
    assert draft["created_at"].endswith("Z") and draft["approved_at"] is None

    detail = world.client.get(f"{V1}/scans/{world.scan_id}", headers=world.headers).json()
    reportable = [r for r in detail["results"] if r["status"] in ("fail", "warn")]
    assert len(reportable) == 6  # readme, tests, ci, license, gitignore, docs
    assert draft["title"] == "GitWell: 6 quality check(s) need attention (score 22/100)"

    body: str = draft["body"]
    assert body.startswith("GitWell scanned this repository at commit `aaaaaaa` on ")
    assert "## ❌ Failing" in body and "## ⚠️ Warnings" not in body  # all six are failures
    positions = [body.index(f"- [ ] **{r['rule_name']}**") for r in reportable]
    assert positions == sorted(positions)  # display_order
    for rule in reportable:
        assert f"**{rule['rule_name']}**: {rule['message']}" in body
        first_tip_line = rule["fix_tip"].splitlines()[0]
        assert f"  {first_tip_line}" in body  # the fix tip follows, indented
    assert "No committed secrets" not in body and "Pinned dependencies" not in body  # pass / N/A
    assert body.endswith("---\n_Generated by GitWell. Score: 22/100 (F)._")
    assert "gitwell-draft" not in body  # the dedupe marker is never in the editable body


