def test_the_secrets_item_never_exposes_paths_lines_patterns_or_values(world: World) -> None:
    world.rescan(
        {
            **GOOD_FILES,
            "src/@scope/keys.py": f"KEY = '{AWS_KEY}'",
            "deploy/id_rsa.pem": "-----BEGIN " + "RSA PRIVATE KEY-----",
        }
    )
    body = world.draft()["body"]
    assert "**No committed secrets**: Potential secrets were detected." in body
    for forbidden in (
        "keys.py",
        "id_rsa",
        "src/",
        "aws_access_key_id",
        "private_key",
        AWS_KEY,
        "@scope",
        ":1",
        "potential secret(s)",
    ):
        assert forbidden not in body, forbidden
    assert "Revoke and rotate the credential first" in body  # the fix tip still follows


def test_an_at_sign_in_a_repo_derived_message_is_defused(world: World, db: Session) -> None:
    scan = Scan(
        repo_id=world.repo["id"],
        status=ScanStatus.completed,
        trigger=ScanTrigger.manual,
        score=50,
        grade="D",
        commit_sha="c" * 40,
    )
    db.add(scan)
    db.commit()
    db.add(
        ScanResult(
            scan_id=scan.id,
            rule_id="tests",
            status=RuleStatus.fail,
            weight=15,
            display_order=30,
            message="No tests under packages/@scope/pkg; ping @octocat",
            details={},
        )
    )
    db.commit()
    body = world.create(scan.id).json()["body"]
    assert f"packages/@{ZWSP}scope/pkg" in body and f"@{ZWSP}octocat" in body
    assert "@scope" not in body and "@octocat" not in body
    # a "fix tip" is trusted static text and keeps its copy-pasteable form
    assert "actions/checkout@v4" not in body  # the ci rule passed here, so it is absent


