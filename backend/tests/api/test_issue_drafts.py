def test_only_completed_scans_can_be_reported(world: World, db: Session) -> None:
    other = world.gh.add_repo("o", "other", 7)
    other.files = BARE_FILES
    repo2 = world.client.post(
        f"{V1}/repos", headers=world.headers, json={"url": "https://github.com/o/other"}
    ).json()
    for status in (ScanStatus.queued, ScanStatus.running, ScanStatus.failed):
        scan = Scan(repo_id=repo2["id"], status=status, trigger=ScanTrigger.manual)
        db.add(scan)
