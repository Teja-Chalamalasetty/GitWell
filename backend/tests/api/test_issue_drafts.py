def test_the_database_allows_one_open_draft_per_repo_only(world: World, db: Session) -> None:
    from sqlalchemy.exc import IntegrityError

    def row(status: DraftStatus) -> IssueDraft:
        return IssueDraft(
            scan_id=world.scan_id, repo_id=world.repo["id"], title="t", body="b", status=status
        )

    for status in (DraftStatus.drafted, DraftStatus.approved, DraftStatus.posting):
        db.add(row(status))
        db.commit()
        db.add(row(DraftStatus.drafted))
        with pytest.raises(IntegrityError):
            db.commit()
        db.rollback()
        db.execute(text("DELETE FROM issue_drafts"))
        db.commit()
    # finished drafts never block, and there can be many of them
    for status in (
        DraftStatus.posted,
        DraftStatus.posted,
        DraftStatus.discarded,
        DraftStatus.discarded,
    ):
        db.add(row(status))
    db.commit()
    db.add(row(DraftStatus.drafted))
    db.commit()


