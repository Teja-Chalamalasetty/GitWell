def test_get_and_list_with_filters(world: World) -> None:
    first = world.draft()
    world.client.post(f"{V1}/issue-drafts/{first['id']}/discard", headers=world.headers)
    second = world.draft()

    everything = world.client.get(f"{V1}/issue-drafts", headers=world.headers).json()
    assert everything["total"] == 2
    assert [d["id"] for d in everything["items"]] == [second["id"], first["id"]]  # newest first
    assert everything["items"][0]["repo_full_name"] == "o/r"

    only_open = world.client.get(
        f"{V1}/issue-drafts", headers=world.headers, params={"status": "drafted"}
    ).json()
    assert [d["id"] for d in only_open["items"]] == [second["id"]]
    by_repo = world.client.get(
        f"{V1}/issue-drafts", headers=world.headers, params={"repo_id": world.repo["id"]}
    ).json()
    assert by_repo["total"] == 2
    assert (
        world.client.get(
            f"{V1}/issue-drafts", headers=world.headers, params={"repo_id": 9999}
        ).json()["total"]
        == 0
    )
    page = world.client.get(
        f"{V1}/issue-drafts", headers=world.headers, params={"limit": 1, "offset": 1}
    ).json()
    assert page["total"] == 2 and page["items"][0]["id"] == first["id"]
    assert (
        world.client.get(
            f"{V1}/issue-drafts", headers=world.headers, params={"status": "nope"}
        ).status_code
        == 422
    )

    assert world.get(second["id"])["id"] == second["id"]
    assert world.client.get(f"{V1}/issue-drafts/9999", headers=world.headers).status_code == 404


def test_viewers_can_read_drafts_but_not_change_them(world: World) -> None:
    draft = world.draft()
    viewer = login_as(world.client, "v@example.com", UserRole.viewer)
    assert world.client.get(f"{V1}/issue-drafts", headers=viewer).status_code == 200
    assert world.client.get(f"{V1}/issue-drafts/{draft['id']}", headers=viewer).status_code == 200
    for method, path in (("patch", ""), ("post", "/approve"), ("post", "/discard")):
        r = getattr(world.client, method)(
            f"{V1}/issue-drafts/{draft['id']}{path}",
            headers=viewer,
            **({"json": {"title": "x"}} if method == "patch" else {}),
        )
        assert r.status_code == 403, path
    assert world.get(draft["id"])["status"] == "drafted"


