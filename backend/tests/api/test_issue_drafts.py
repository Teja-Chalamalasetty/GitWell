def test_discard_from_drafted_and_from_approved(world: World) -> None:
    first = world.draft()
    r = world.client.post(f"{V1}/issue-drafts/{first['id']}/discard", headers=world.headers)
    assert r.status_code == 200 and r.json()["status"] == "discarded"

    second = world.draft()
    world.gh.repo.post_mode = 500
    world.client.post(f"{V1}/issue-drafts/{second['id']}/approve", headers=world.headers)
    assert world.get(second["id"])["status"] == "approved"
    r = world.client.post(f"{V1}/issue-drafts/{second['id']}/discard", headers=world.headers)
    assert r.status_code == 200 and r.json()["status"] == "discarded"


def test_discard_from_other_states_is_409(world: World, db: Session) -> None:
    draft = world.draft()
    for status in (DraftStatus.posting, DraftStatus.posted, DraftStatus.discarded):
        db.execute(
            text("UPDATE issue_drafts SET status = :s WHERE id = :i"),
            {"s": status.value, "i": draft["id"]},
        )
        db.commit()
        r = world.client.post(f"{V1}/issue-drafts/{draft['id']}/discard", headers=world.headers)
        assert r.status_code == 409 and r.json()["error"]["code"] == "INVALID_STATE", status
    assert (
        world.client.post(f"{V1}/issue-drafts/9999/discard", headers=world.headers).status_code
        == 404
    )


